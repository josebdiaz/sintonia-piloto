def svg(paths):
    body = "".join(f'<path d="{d}"/>' for d in paths)
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
            f'aria-hidden="true" focusable="false">{body}</svg>\n')


def main():
    out = Path(__file__).resolve().parent.parent / "assets" / "iconos"
    out.mkdir(parents=True, exist_ok=True)
    for name, paths in ICONOS.items():
        (out / f"{name}.svg").write_text(svg(paths), encoding="utf-8")
    sprite = "".join(f'<symbol id="i-{n}" viewBox="0 0 24 24">' + "".join(f'<path d="{d}"/>' for d in p) + "</symbol>"
                     for n, p in ICONOS.items())
    (out / "sprite.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" fill="none" stroke="currentColor" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{sprite}</svg>\n', encoding="utf-8")
    print(f"{len(ICONOS)} íconos + sprite.svg en {out}")


if __name__ == "__main__":
    main()
